  sort_order integer not null default 0,
  primary key(anime_id,related_anime_id,relation_type),
  check(anime_id <> related_anime_id)
);

create table if not exists public.anime_external_ids (
  anime_id bigint primary key references public.anime(id) on delete cascade,
  mal_id bigint,
  anilist_id bigint,
