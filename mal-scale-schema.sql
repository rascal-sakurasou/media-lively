);

create table if not exists public.anime_reviews (
  id bigint generated by default as identity primary key,
  anime_id bigint not null references public.anime(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text,
  body text not null check(char_length(body) between 1 and 10000),
  score numeric(3,1) not null check(score >= 0 and score <= 10),
  spoiler boolean not null default false,
  helpful_count integer not null default 0,
  comment_count integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.review_reactions (
  review_id bigint not null references public.anime_reviews(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  reaction text not null default 'helpful' check(reaction in ('helpful','like')),
  created_at timestamptz not null default now(),
  primary key(review_id,user_id,reaction)
);

create table if not exists public.anime_review_comments (
  id bigint generated by default as identity primary key,
  review_id bigint not null references public.anime_reviews(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  body text not null check(char_length(body) between 1 and 2000),
  created_at timestamptz not null default now()
);

create table if not exists public.anime_follows (
  user_id uuid not null references auth.users(id) on delete cascade,
  anime_id bigint not null references public.anime(id) on delete cascade,
  created_at timestamptz not null default now(),
