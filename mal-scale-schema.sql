-- 管理者判定用関数。クライアントからservice_roleを扱わない。
create or replace function public.is_admin_user()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and is_admin = true
  );
$$;

-- 評価スコア。評価数の少ない作品が偶然上位に来ることを抑えるためのベイズ平均。
create or replace view public.anime_rating_stats as
select
  a.id as anime_id,
  coalesce(count(ul.score) filter (where ul.score is not null),0)::bigint as rating_count,
  coalesce(avg(ul.score) filter (where ul.score is not null),0)::numeric(4,2) as average_score
from public.anime a
left join public.anime_user_list ul on ul.anime_id = a.id
group by a.id;

