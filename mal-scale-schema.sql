create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null,
  display_name text,
  bio text,
  avatar_url text,
  is_admin boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.anime_user_list (
  user_id uuid not null references auth.users(id) on delete cascade,
  anime_id bigint not null references public.anime(id) on delete cascade,
  status text not null default 'plan' check(status in ('plan','watching','completed','dropped','paused','rewatching')),
  score numeric(3,1) check(score >= 0 and score <= 10),
  progress integer not null default 0 check(progress >= 0),
  is_favorite boolean not null default false,
  notes text,
  started_at date,
  completed_at date,
  updated_at timestamptz not null default now(),
