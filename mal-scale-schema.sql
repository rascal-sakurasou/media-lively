-- 再実行時の衝突を避けるため、この拡張SQLでは既存ポリシーの削除を行わない。
-- Supabase Dashboardで同名ポリシーが既にある場合は、そのポリシーを整理してから実行してください。

do $$
begin
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='profiles' and policyname='profiles public read') then
    create policy "profiles public read" on public.profiles for select using (true);
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='profiles' and policyname='profiles own insert') then
    create policy "profiles own insert" on public.profiles for insert with check (auth.uid() = id);
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='profiles' and policyname='profiles own update') then
    create policy "profiles own update" on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id);
  end if;

  if not exists (select 1 from pg_policies where schemaname='public' and tablename='anime_user_list' and policyname='mylist own read') then
    create policy "mylist own read" on public.anime_user_list for select using (auth.uid() = user_id);
    create policy "mylist own insert" on public.anime_user_list for insert with check (auth.uid() = user_id);
    create policy "mylist own update" on public.anime_user_list for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
    create policy "mylist own delete" on public.anime_user_list for delete using (auth.uid() = user_id);
  end if;

  if not exists (select 1 from pg_policies where schemaname='public' and tablename='anime_reviews' and policyname='reviews public read') then
    create policy "reviews public read" on public.anime_reviews for select using (true);
    create policy "reviews own insert" on public.anime_reviews for insert with check (auth.uid() = user_id);
    create policy "reviews own update" on public.anime_reviews for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
    create policy "reviews own delete" on public.anime_reviews for delete using (auth.uid() = user_id);
  end if;

  if not exists (select 1 from pg_policies where schemaname='public' and tablename='review_reactions' and policyname='review reactions public read') then
    create policy "review reactions public read" on public.review_reactions for select using (true);
    create policy "review reactions own write" on public.review_reactions for insert with check (auth.uid() = user_id);
    create policy "review reactions own delete" on public.review_reactions for delete using (auth.uid() = user_id);
  end if;

  if not exists (select 1 from pg_policies where schemaname='public' and tablename='anime_review_comments' and policyname='review comments public read') then
    create policy "review comments public read" on public.anime_review_comments for select using (true);
    create policy "review comments own insert" on public.anime_review_comments for insert with check (auth.uid() = user_id);
    create policy "review comments own delete" on public.anime_review_comments for delete using (auth.uid() = user_id);
  end if;

  if not exists (select 1 from pg_policies where schemaname='public' and tablename='anime_follows' and policyname='anime follows own read') then
    create policy "anime follows own read" on public.anime_follows for select using (auth.uid() = user_id);
    create policy "anime follows own insert" on public.anime_follows for insert with check (auth.uid() = user_id);
    create policy "anime follows own delete" on public.anime_follows for delete using (auth.uid() = user_id);
  end if;

