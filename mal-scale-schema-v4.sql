create or replace view public.anime_discovery as
select
  a.id,
  a.title,
  coalesce(a.title_en, a.english_title) as title_en,
  a.title_romaji,
  a.title_kana,
  a.genre,
  a.description,
  a.type,
  a.status,
  a.season,
  a.season_year,
  a.episodes,
  a.poster_url,
  a.view_count,
  a.popularity_count,
  coalesce(rs.rating_count,0) as rating_count,
  coalesce(rs.average_score,0) as average_score,
  coalesce(rs.bayesian_score,0) as bayesian_score
from public.anime a
left join public.anime_rating_stats rs on rs.anime_id = a.id;

commit;
