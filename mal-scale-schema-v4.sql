create or replace function public.is_admin_user()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists(select 1 from public.profiles where id = auth.uid() and is_admin = true);
$$;

-- Public read policies for catalogue/community.
do $$
begin
  create policy "profiles public read" on public.profiles for select using (true);
exception when duplicate_object then null; end $$;

do $$
begin
  create policy "profiles own write" on public.profiles for all using (auth.uid() = id or public.is_admin_user()) with check (auth.uid() = id or public.is_admin_user());
exception when duplicate_object then null; end $$;

do $$
begin
  create policy "mylist own all" on public.anime_user_list for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
exception when duplicate_object then null; end $$;

do $$
begin
  create policy "anime follows own all" on public.anime_follows for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
exception when duplicate_object then null; end $$;

do $$
begin
  create policy "user follows public read" on public.user_follows for select using (true);
  create policy "user follows own write" on public.user_follows for all using (auth.uid() = follower_id) with check (auth.uid() = follower_id);
