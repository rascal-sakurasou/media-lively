-- 7. Rating stats refresh
-- =========================
create or replace function public.refresh_anime_rating_stats(p_anime_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count bigint;
  v_avg numeric(4,2);
  v_global numeric(4,2);
  v_min_count numeric := 10;
  v_bayes numeric(5,3);
begin
  select count(*), coalesce(avg(score),0) into v_count, v_avg
  from public.anime_user_list where anime_id = p_anime_id and score is not null;
  select coalesce(avg(score),0) into v_global
  from public.anime_user_list where score is not null;
  v_bayes := case when v_count = 0 then 0 else ((v_count/(v_count+v_min_count))*v_avg) + ((v_min_count/(v_count+v_min_count))*v_global) end;
  insert into public.anime_rating_stats(anime_id,rating_count,average_score,bayesian_score,updated_at)
  values(p_anime_id,v_count,v_avg,v_bayes,now())
  on conflict(anime_id) do update set rating_count=excluded.rating_count, average_score=excluded.average_score, bayesian_score=excluded.bayesian_score, updated_at=now();
end;
$$;

create or replace function public.refresh_rating_stats_trigger()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public.refresh_anime_rating_stats(coalesce(new.anime_id, old.anime_id));
  return coalesce(new, old);
end;
$$;

drop trigger if exists trg_refresh_rating_stats on public.anime_user_list;
create trigger trg_refresh_rating_stats
after insert or update of score or delete on public.anime_user_list
for each row execute function public.refresh_rating_stats_trigger();

